"""Бот-гороскоп: собирает «предсказание» из случайных частей по выбранному знаку."""

import random

import telebot

from config import TOKEN

bot = telebot.TeleBot(TOKEN)

FIRST = [
    "Сегодня — идеальный день для новых начинаний.",
    "Оптимальный день для того, чтобы решиться на смелый поступок!",
    "Будьте осторожны, сегодня звёзды могут повлиять на ваше финансовое состояние.",
    "Лучшее время для того, чтобы начать новые отношения или разобраться со старыми.",
    "Плодотворный день для того, чтобы разобраться с накопившимися делами.",
]
SECOND = [
    "Но помните, что даже в этом случае нужно не забывать про",
    "Если поедете за город, заранее подумайте про",
    "Те, кто сегодня нацелен выполнить множество дел, должны помнить про",
    "Если у вас упадок сил, обратите внимание на",
    "Помните, что мысли материальны, а значит вам нужно думать про",
]
SECOND_ADD = [
    "отношения с друзьями и близкими.",
    "работу и деловые вопросы.",
    "себя и своё здоровье.",
    "бытовые вопросы — особенно те, которые вы не доделали вчера.",
    "отдых, чтобы не превратить себя в загнанную лошадь.",
]
THIRD = [
    "Злые языки могут говорить вам обратное, но сегодня их слушать не нужно.",
    "Знайте, что успех благоволит только настойчивым.",
    "Даже если вы не сможете уменьшить влияние ретроградного Меркурия — доведите дела до конца.",
    "Не нужно бояться одиноких встреч — сегодня они значат многое.",
    "Если встретите незнакомца на пути — проявите участие.",
]
SIGNS = ["♈ Овен", "♉ Телец", "♊ Близнецы", "♋ Рак", "♌ Лев", "♍ Дева",
         "♎ Весы", "♏ Скорпион", "♐ Стрелец", "♑ Козерог", "♒ Водолей", "♓ Рыбы"]


def horoscope() -> str:
    return f"{random.choice(FIRST)} {random.choice(SECOND)} {random.choice(SECOND_ADD)} {random.choice(THIRD)}"


@bot.message_handler(commands=["start"])
def start(message):
    bot.reply_to(message, "🔮 Привет! Я бот-гороскоп. Напишите /zodiac, чтобы выбрать знак.")


@bot.message_handler(commands=["zodiac"])
def zodiac(message):
    signs = "\n".join(f"{i} {s}" for i, s in enumerate(SIGNS, 1))
    bot.reply_to(message, f"🌟 Отправьте номер знака:\n{signs}")


@bot.message_handler(content_types=["text"])
def handle(message):
    try:
        number = int(message.text)
    except ValueError:
        bot.reply_to(message, "⚠️ Отправьте число от 1 до 12 или /zodiac для списка.")
        return
    if 1 <= number <= 12:
        bot.reply_to(message, f"🔮 Гороскоп для знака {SIGNS[number - 1]}:\n\n{horoscope()}")
    else:
        bot.reply_to(message, "⚠️ Выберите число от 1 до 12.")


if __name__ == "__main__":
    print("🚀 Бот-гороскоп запущен")
    bot.infinity_polling()
